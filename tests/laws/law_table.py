def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def law_rows(law: str, lang: str) -> list[str]:
    t = TEXT[lang]
    module = MODULES[law]
    lines = [f"## {t['laws'][law]}", "", t["header"], "|---|---|---|---|---|---|"]
    notes = []
    for subject in SUBJECTS:
        exp = expectation(law, subject)
        status = t["status"][exp.status]
        if exp.status == OUT_OF_SCOPE:
            lines.append(f"| `{subject}` | {status} | — | — | — | — |")
            notes.append(f"- `{subject}` ({status}): {exp.reason}")
            continue
        notes.append(f"- `{subject}` ({status}): {exp.reason}")
        for check, judge in module.CHECKS.items():
            ok, value = judge(subject)
            if exp.status == CONTROL:
                expected = "—"
            else:
                expected = t["xfail"] if check in exp.xfail else t["pass"]
            result = t["pass"] if ok else t["fail"]
            label = f"{check}: {module.CHECK_LABELS[check]}"
            lines.append(
                f"| `{subject}` | {status} | {_cell(label)} | {expected} | {result} | {value} |"
            )
            if check in exp.xfail:
                notes.append(f"  - {check} (xfail): {exp.xfail[check]}")
    return [*lines, "", f"{t['reasons']}:", "", *notes, ""]


def render(lang: str) -> str:
    t = TEXT[lang]
    parts = [t["title"], "", t["switch"], "", t["intro"], ""]
    for law in MODULES:
        parts.extend(law_rows(law, lang))
    return "\n".join(parts).rstrip() + "\n"


def doc_path(lang: str) -> Path:
    return DOCS / lang / "law-suite.md"


def main() -> None:
    for lang in TEXT:
        path = doc_path(lang)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(lang), encoding="utf-8")
        print(path)


if __name__ == "__main__":
    main()
